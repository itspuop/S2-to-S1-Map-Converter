"""Decode all CMapMesh nodes and export safe convex solids into one VMF.

Progress is printed as meshes are processed. The VMF is created early and appended
incrementally, so a large map does not leave the user waiting without feedback.
"""
from __future__ import annotations
import argparse, json, sys, time, re
from pathlib import Path

from s2css.dmx_binary import DMXError, parse_binary_v9
from s2css.mesh_decode import MeshDecodeError, decode_polygon_mesh
from s2css.vmf_export import (
    MeshExportError, _extract_mesh, _source_transform, _plane_points, _vmf_side,
    validate_convex_brush,
)


def _vmf_header() -> str:
    return (
        "// Generated by S2ToCSS Converter. Review in Hammer before compiling.\n"
        "versioninfo\n{\n"
        ' "editorversion" "400"\n "editorbuild" "0"\n "mapversion" "1"\n "formatversion" "100"\n "prefab" "0"\n}\n'
        "visgroups\n{\n}\nviewsettings\n{\n"
        ' "bSnapToGrid" "1"\n "bShowGrid" "1"\n "bShowLogicalGrid" "0"\n "nGridSpacing" "64"\n "bShow3DGrid" "0"\n}\n'
        'world\n{\n "id" "1"\n'
        ' "mapversion" "1"\n "classname" "worldspawn"\n "detailmaterial" "detail/detailsprites"\n "detailvbsp" "detail.vbsp"\n "maxpropscreenwidth" "-1"\n "skyname" "sky_day01_01"\n'
    )


def _geometry_metrics(vertices, faces) -> dict:
    """Compact size diagnostics to identify malformed or unexpectedly huge meshes."""
    if not vertices:
        return {}
    mins = [min(v[k] for v in vertices) for k in range(3)]
    maxs = [max(v[k] for v in vertices) for k in range(3)]
    max_edge = 0.0
    max_face_span = 0.0
    max_face_index = None
    for fi, face in enumerate(faces):
        points = [vertices[i] for i in face]
        for j, p in enumerate(points):
            q = points[(j + 1) % len(points)]
            length = sum((p[k] - q[k]) ** 2 for k in range(3)) ** 0.5
            if length > max_edge:
                max_edge = length
        span = 0.0
        for i, p in enumerate(points):
            for q in points[i + 1:]:
                span = max(span, sum((p[k] - q[k]) ** 2 for k in range(3)) ** 0.5)
        if span > max_face_span:
            max_face_span = span
            max_face_index = fi
    size = [maxs[k] - mins[k] for k in range(3)]
    return {
        "bounds_min": [round(v, 4) for v in mins],
        "bounds_max": [round(v, 4) for v in maxs],
        "bounds_size": [round(v, 4) for v in size],
        "max_dimension": round(max(size), 4),
        "max_edge_length": round(max_edge, 4),
        "largest_face_span": round(max_face_span, 4),
        "largest_face_index": max_face_index,
    }


def _material_diagnostics(elements: list[dict], mesh_attrs: dict) -> dict:
    """Capture Source 2 material references and per-face material fields for later mapping."""
    material_keys = ("material", "texture", "vmat", "shader", "albedo", "basecolor", "base_color")
    related = {
        key: value for key, value in mesh_attrs.items()
        if any(token in key.lower().replace("_", "") for token in material_keys)
    }
    assignment_candidates = {
        key: value for key, value in mesh_attrs.items()
        if "face" in key.lower() and "material" in key.lower()
        or "material" in key.lower() and any(token in key.lower() for token in ("index", "indices", "slot", "id"))
    }
    materials = mesh_attrs.get("materials", [])
    resolved_materials = []
    if isinstance(materials, list):
        for value in materials:
            if isinstance(value, dict) and isinstance(value.get("element_index"), int):
                index = value["element_index"]
                if 0 <= index < len(elements):
                    element = elements[index]
                    attrs = element.get("attributes", {})
                    relevant_attrs = {
                        key: val for key, val in attrs.items()
                        if any(token in key.lower().replace("_", "") for token in material_keys)
                        or key.lower() in ("name", "path", "materialname", "materialpath")
                    }
                    resolved_materials.append({
                        "element_index": index,
                        "type": element.get("type"),
                        "name": element.get("name"),
                        "guid": element.get("guid"),
                        "relevant_attributes": relevant_attrs,
                    })
                else:
                    resolved_materials.append({"element_index": index, "error": "reference out of range"})
            else:
                resolved_materials.append(value)
    return {
        "source2_materials": materials,
        "resolved_material_elements": resolved_materials,
        "material_related_mesh_attributes": related,
        "mesh_attribute_keys": sorted(mesh_attrs.keys()),
        "possible_face_material_assignments": assignment_candidates,
    }



def _scan_source2_materials(elements: list[dict], materials_root: Path | None) -> dict:
    """Report VMAT and texture availability in addon/shared asset roots; no conversion."""
    refs = set()
    for element in elements:
        attrs = element.get("attributes", {}) if isinstance(element, dict) else {}
        values = attrs.get("materials", [])
        if isinstance(values, list):
            for value in values:
                if isinstance(value, str) and value.lower().endswith(".vmat"):
                    refs.add(value.replace("\\", "/").lstrip("/"))

    report = {
        "materials_root": str(materials_root) if materials_root else None,
        "referenced_vmat_count": len(refs),
        "materials": [],
        "texture_roots": [],
    }
    if not materials_root:
        report["note"] = "No materials folder selected."
        return report

    # Build likely roots only from the selected path. Include them only when present;
    # never assume the user's install layout or search the entire drive.
    roots = [("selected_addon_content", materials_root)]
    parts_lower = [part.lower() for part in materials_root.parts]
    content_index = next((i for i in range(len(parts_lower) - 1, -1, -1) if parts_lower[i] == "content"), None)
    if content_index is not None:
        content_root = Path(*materials_root.parts[:content_index + 1])
        game_root = Path(*materials_root.parts[:content_index], "game")
        candidates = [
            ("addon_game", game_root.joinpath(*materials_root.parts[content_index + 1:])),
            ("shared_content", content_root / "csgo" / "materials"),
            ("shared_game", game_root / "csgo" / "materials"),
        ]
        seen = {str(path).casefold() for _, path in roots}
        for label, path in candidates:
            if path.is_dir() and str(path).casefold() not in seen:
                roots.append((label, path))
                seen.add(str(path).casefold())
    report["texture_roots"] = [{"label": label, "path": str(path), "exists": path.is_dir()} for label, path in roots]

    def asset_candidates(asset_ref: str, suffix: str | None = None) -> list[dict]:
        normalized = asset_ref.replace("\\", "/").strip().lstrip("/")
        if normalized.lower().startswith("materials/"):
            normalized = normalized[len("materials/"):]
        if suffix:
            normalized = str(Path(normalized).with_suffix(suffix))
        matches = []
        for label, root in roots:
            candidate = root / Path(normalized)
            if candidate.is_file():
                matches.append({"root": label, "path": str(candidate)})
        return matches

    texture_pattern = re.compile(r'"([^"]+\.(?:tga|png|jpg|jpeg|psd|vtf|vtex|mks))"', re.I)
    for ref in sorted(refs):
        normalized = ref[len("materials/"):] if ref.lower().startswith("materials/") else ref
        vmat_matches = asset_candidates(ref)
        item = {
            "vmat_path": ref,
            "resolved_file": str(materials_root / Path(normalized)),
            "exists": bool(vmat_matches),
            "found_in": vmat_matches,
        }
        source_path = next((Path(match["path"]) for match in vmat_matches if Path(match["path"]).suffix.lower() == ".vmat"), None)
        if source_path:
            try:
                content = source_path.read_text(encoding="utf-8-sig", errors="replace")
                shader = re.search(r'"(?:shader|m_shaderName)"\s+"([^"]+)"', content, re.I)
                if shader:
                    item["shader"] = shader.group(1)
                texture_refs = []
                for match in texture_pattern.finditer(content):
                    texture_ref = match.group(1).replace("\\", "/")
                    if texture_ref.lower().startswith("materials/") and texture_ref.lower().endswith(".mks"):
                        continue
                    if texture_ref.lower().endswith((".tga", ".png", ".jpg", ".jpeg", ".psd", ".vtf", ".vtex")):
                        texture_refs.append(texture_ref)
                # Preserve order while removing duplicate references.
                texture_refs = list(dict.fromkeys(texture_refs))
                item["textures"] = [
                    {"texture_path": texture_ref,
                     "found_in": asset_candidates(texture_ref),
                     "exists": bool(asset_candidates(texture_ref))}
                    for texture_ref in texture_refs
                ]
                item["texture_reference_count"] = len(texture_refs)
            except OSError as exc:
                item["read_error"] = str(exc)
        report["materials"].append(item)
    report["note"] = (
        "Availability scan only. VMAT/VTexture conversion to VMT/VTF is not implemented. "
        "Material-slot presence does not establish which material belongs to each face."
    )
    return report

def export_vmap_to_vmf(vmap_path: Path, output_path: Path, report_path: Path | None = None, materials_root: Path | None = None) -> dict:
    started = time.monotonic()
    print(f"[1/3] Parsing editable VMAP: {vmap_path}", flush=True)
    graph = parse_binary_v9(vmap_path, include_binary=False)
    graph["source_file"] = str(vmap_path)
    elements = graph.get("elements", [])
    mesh_nodes = [(i, n) for i, n in enumerate(elements) if n.get("type") == "CMapMesh"]
    total = len(mesh_nodes)
    material_scan = _scan_source2_materials(elements, materials_root)
    print(f"Material scan: {material_scan['referenced_vmat_count']} referenced VMAT path(s).", flush=True)
    meshdata_users = {}
    for mesh_i, mesh_node in mesh_nodes:
        mesh_ref = mesh_node.get("attributes", {}).get("meshData")
        mesh_ref_i = mesh_ref.get("element_index") if isinstance(mesh_ref, dict) else None
        if isinstance(mesh_ref_i, int):
            meshdata_users.setdefault(mesh_ref_i, []).append(mesh_i)
    print(f"[2/3] Found {total:,} CMapMesh nodes across {len(elements):,} DMX elements.", flush=True)
    processing_started = time.monotonic()
    # Complex meshes are intended for the user to convert to models in Hammer.
    # Bound worst-case validation time instead of letting one mesh stall the batch.
    MAX_EDGES = 5000
    MAX_FACES = 1500
    MAX_VERTEX_FACE_PRODUCT = 2_000_000
    if total == 0:
        print("No CMapMesh nodes were found; writing an empty world VMF.", flush=True)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    # Write the header up front, then append solids as each mesh completes.
    with output_path.open("w", encoding="utf-8", newline="\n") as vmf:
        vmf.write(_vmf_header())
        vmf.flush()
        results = []
        next_id = 2
        exported = 0
        skipped = 0
        for ordinal, (index, node) in enumerate(mesh_nodes, start=1):
            item = {"cmapmesh_element_index": index, "name": node.get("name"), "guid": node.get("guid")}
            mesh_started = time.monotonic()
            attrs = node.get("attributes", {})
            mesh_ref = attrs.get("meshData")
            mesh_index = mesh_ref.get("element_index") if isinstance(mesh_ref, dict) else None
            item["meshData_index"] = mesh_index
            item["meshData_shared_by_CMapMesh_elements"] = meshdata_users.get(mesh_index, []) if isinstance(mesh_index, int) else []
            mesh_attrs = elements[mesh_index].get("attributes", {}) if isinstance(mesh_index, int) and 0 <= mesh_index < len(elements) else {}
            item["vertexData_index"] = mesh_attrs.get("vertexData", {}).get("element_index") if isinstance(mesh_attrs.get("vertexData"), dict) else None
            item.update(_material_diagnostics(elements, mesh_attrs))
            edge_count = len(mesh_attrs.get("edgeNextIndices", [])) if isinstance(mesh_attrs.get("edgeNextIndices"), list) else 0
            face_count = len(mesh_attrs.get("faceEdgeIndices", [])) if isinstance(mesh_attrs.get("faceEdgeIndices"), list) else 0
            # Announce the current mesh before decoding, so a single expensive mesh is visible.
            print(f"  Processing mesh {ordinal:,}/{total:,} (element {index}, edges {edge_count:,}, faces {face_count:,})...", flush=True)
            try:
                if edge_count > MAX_EDGES or face_count > MAX_FACES:
                    item.update({"status": "manual_or_unsupported", "reason": f"Mesh exceeds safe brush-export limit ({edge_count} edges / {face_count} faces; limits {MAX_EDGES} / {MAX_FACES}). Convert this complex mesh to a model in Hammer."})
                    skipped += 1
                    decoded = None
                else:
                    decoded = decode_polygon_mesh(graph, index)
                if decoded is None:
                    positions, faces = [], []
                else:
                    positions, faces = _extract_mesh(decoded)
                origin = decoded.get("origin", [0, 0, 0]) if decoded else [0, 0, 0]
                angles = decoded.get("angles", [0, 0, 0]) if decoded else [0, 0, 0]
                scales = decoded.get("scales", [1, 1, 1]) if decoded else [1, 1, 1]
                vertices = [_source_transform(p, origin, angles, scales) for p in positions]
                if decoded is not None:
                    item["position_stream_source"] = decoded.get("position_stream_source")
                    item["position_stream_candidates"] = decoded.get("position_stream_candidates", [])
                    item["local_geometry_metrics"] = _geometry_metrics(positions, faces)
                    item["geometry_metrics"] = _geometry_metrics(vertices, faces)
                    # Preserve topology details for meshes that may pass validation but export
                    # incorrectly. Duplicate coordinates with different indices can hide broken
                    # topology from index-based manifold checks.
                    duplicate_position_pairs = []
                    for pi, p in enumerate(positions):
                        for qi in range(pi + 1, len(positions)):
                            q = positions[qi]
                            if all(abs(float(p[k]) - float(q[k])) <= 1e-5 for k in range(3)):
                                duplicate_position_pairs.append([pi, qi])
                    diagnostic_flags = []
                    if duplicate_position_pairs:
                        diagnostic_flags.append("duplicate_position_coordinates")
                    if len(positions) >= 8 and len(faces) < 6:
                        diagnostic_flags.append("fewer_than_six_faces_for_mesh_with_eight_or_more_position_entries")
                    if item["local_geometry_metrics"].get("max_dimension", 0) > 8192:
                        diagnostic_flags.append("very_large_local_bounds")
                    if diagnostic_flags:
                        item["diagnostic_flags"] = diagnostic_flags
                        item["duplicate_position_index_pairs"] = duplicate_position_pairs
                        item["local_positions"] = positions
                        item["face_loops"] = faces
                        item["transformed_positions"] = vertices
                if decoded is None:
                    validation = None
                elif len(vertices) * len(faces) > MAX_VERTEX_FACE_PRODUCT:
                    validation = {"valid": False, "issues": [f"Validation complexity limit exceeded ({len(vertices)} vertices x {len(faces)} faces); convert this complex mesh to a model in Hammer."]}
                else:
                    validation = validate_convex_brush(vertices, faces)
                    # Index-based topology checks can miss duplicate faces when different
                    # vertex indices contain the same coordinates. Compare each face by
                    # its rounded geometric vertex set, independent of winding/order.
                    face_signatures = {}
                    duplicate_geometric_face_pairs = []
                    for face_index, face in enumerate(faces):
                        signature = tuple(sorted(
                            tuple(round(float(vertices[vertex_index][axis]), 4) for axis in range(3))
                            for vertex_index in face
                        ))
                        if signature in face_signatures:
                            duplicate_geometric_face_pairs.append([face_signatures[signature], face_index])
                        else:
                            face_signatures[signature] = face_index
                    if duplicate_geometric_face_pairs:
                        validation["valid"] = False
                        validation.setdefault("issues", []).append(
                            f"Duplicate geometric faces detected (same coordinates with same or reversed winding): {duplicate_geometric_face_pairs}"
                        )
                        item["duplicate_geometric_face_pairs"] = duplicate_geometric_face_pairs
                if decoded is not None:
                    item["validation"] = validation
                    item["counts"] = decoded.get("counts")
                if decoded is None:
                    pass  # Preflight already marked this oversized mesh as skipped.
                elif not validation["valid"]:
                    item.update({"status": "manual_or_unsupported", "reason": "; ".join(validation["issues"])})
                    skipped += 1
                else:
                    center = tuple(sum(v[k] for v in vertices) / len(vertices) for k in range(3))
                    item["vmf_solid_id"] = next_id
                    # Keep a source-mesh marker in the VMF text so exported solids can be traced.
                    vmf.write(f' // Source CMapMesh element {index} | GUID {node.get("guid")}\n')
                    vmf.write(f' solid\n {{\n  "id" "{next_id}"\n')
                    next_id += 1
                    # Use the shared VMF plane writer; it corrects face winding for Source 1 brush planes.
                    for face in faces:
                        a, b, c = _plane_points(face, vertices, center)
                        vmf.write(_vmf_side(next_id, a, b, c, "TOOLS/TOOLSNODRAW"))
                        next_id += 1
                    vmf.write('  editor\n  {\n   "color" "0 0 0"\n   "visgroupshown" "1"\n   "visgroupautoshown" "1"\n  }\n }\n')
                    vmf.flush()
                    exported += 1
                    item["status"] = "exported_brush"
                    item["transform"] = {"origin": origin, "angles": angles, "scales": scales}
            except (MeshDecodeError, MeshExportError, TypeError, ValueError, IndexError, KeyError) as exc:
                item.update({"status": "manual_or_unsupported", "reason": str(exc)})
                skipped += 1
            results.append(item)

            # Keep the console responsive and persist the report during long conversions.
            mesh_elapsed = time.monotonic() - mesh_started
            print(f"    Finished mesh {ordinal:,}/{total:,} in {mesh_elapsed:.2f}s | brushes {exported:,} | skipped {skipped:,}", flush=True)
            if ordinal == 1 or ordinal % 10 == 0 or ordinal == total:
                elapsed = time.monotonic() - processing_started
                rate = ordinal / elapsed if elapsed > 0 else 0
                eta = (total - ordinal) / rate if rate > 0 else 0
                print(f"  Progress {ordinal:,}/{total:,} | elapsed processing {elapsed:.1f}s | ETA ~{eta:.1f}s", flush=True)
                if report_path:
                    partial = {
                        "source_file": str(vmap_path), "output_vmf": str(output_path),
                        "cmapmesh_count": total, "processed_mesh_count": ordinal,
                        "exported_brush_count": exported, "skipped_mesh_count": skipped,
                        "complete": ordinal == total,
                        "material_policy": "All exported faces use TOOLS/TOOLSNODRAW; Source 2 VMAT translation is not implemented.",
                        "material_scan": material_scan,
                        "meshes": results,
                    }
                    report_path.parent.mkdir(parents=True, exist_ok=True)
                    report_path.write_text(json.dumps(partial, indent=2), encoding="utf-8")
        vmf.write("}\n")
        vmf.flush()

    summary = {
        "source_file": str(vmap_path), "output_vmf": str(output_path),
        "cmapmesh_count": total, "processed_mesh_count": total,
        "exported_brush_count": exported, "skipped_mesh_count": skipped,
        "complete": True,
        "elapsed_seconds": round(time.monotonic() - started, 2),
        "material_policy": "All exported faces use TOOLS/TOOLSNODRAW; Source 2 VMAT translation is not implemented.",
        "material_scan": material_scan,
        "meshes": results,
    }
    if report_path:
        report_path.parent.mkdir(parents=True, exist_ok=True)
        report_path.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(f"[3/3] Finished in {summary['elapsed_seconds']:.1f}s.", flush=True)
    return summary


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("vmap", type=Path, help="Editable binary-DMX .vmap, not .vmap_c")
    parser.add_argument("--output", type=Path, help="Output VMF (default: <map>_brushes.vmf)")
    parser.add_argument("--report", type=Path, help="Optional JSON report listing exported and skipped meshes")
    parser.add_argument("--materials-root", type=Path, help="Addon materials folder")
    args = parser.parse_args(argv)
    if not args.vmap.is_file():
        parser.error(f"VMAP file not found: {args.vmap}")
    if args.materials_root is not None and not args.materials_root.is_dir():
        parser.error(f"Materials folder not found: {args.materials_root}")
    output = args.output or args.vmap.with_name(args.vmap.stem + "_brushes.vmf")
    report = args.report or output.with_name(output.stem + "_report.json")
    try:
        result = export_vmap_to_vmf(args.vmap, output, report, args.materials_root)
    except (OSError, DMXError, ValueError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr, flush=True)
        return 1
    print(f"VMF written: {output}", flush=True)
    print(f"Brushes exported: {result['exported_brush_count']} / {result['cmapmesh_count']} CMapMesh nodes", flush=True)
    print(f"Skipped for manual/unsupported handling: {result['skipped_mesh_count']}", flush=True)
    print(f"Mesh report: {report}", flush=True)
    print("Exported faces use TOOLS/TOOLSNODRAW; inspect the VMF in Hammer before compiling.", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
